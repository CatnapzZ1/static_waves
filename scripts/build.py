#!/usr/bin/env python3
"""Build into fresh output; preserve previous local output instead of deleting it."""
import argparse, pathlib, subprocess, tempfile, uuid
parser=argparse.ArgumentParser()
parser.add_argument('--destination', type=pathlib.Path)
args=parser.parse_args()
root=pathlib.Path(__file__).resolve().parent.parent
if args.destination:
    dest=args.destination.absolute()
    if dest.is_symlink() or (dest.exists() and any(p.name!='.release.json' for p in dest.iterdir())):
        raise SystemExit('Refusing a nonempty destination; select a fresh release directory')
    subprocess.run(['hugo','--environment','production','--buildDrafts=false','--buildFuture=false','--buildExpired=false','--destination',str(dest)],cwd=root,check=True)
else:
    public=root/'public'
    if public.is_symlink() or (public.exists() and not (public/'.blog-build-marker').is_file()):
        raise SystemExit('Existing public/ was not created by build.sh; preserve/move it manually first')
    cache=root/'.test-output';cache.mkdir(exist_ok=True)
    dest=pathlib.Path(tempfile.mkdtemp(prefix='build-',dir=cache))
    subprocess.run(['hugo','--environment','production','--buildDrafts=false','--buildFuture=false','--buildExpired=false','--destination',str(dest)],cwd=root,check=True)
    (dest/'.blog-build-marker').write_text('Generated by scripts/build.py\n')
    if public.exists(): public.rename(cache/('previous-public-'+uuid.uuid4().hex))
    dest.rename(public)
    print('PASS production output:',public)
